/**
 * Bundle desktop pet main, preload, and browser renderer for Electron.
 *
 * Usage: node scripts/build-desktop-pet.mjs
 *        npm run desktop:build
 */
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

import { loadDesktopPetAssetValidator } from "./desktop-pet-asset-validator.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outMain = path.join(ROOT, "desktop", "main", "main.js");
const outPreload = path.join(ROOT, "desktop", "preload", "pet-preload.js");
const outRenderer = path.join(ROOT, "desktop", "renderer", "pet-app.js");

async function build() {
  mkdirSync(path.dirname(outMain), { recursive: true });
  mkdirSync(path.dirname(outPreload), { recursive: true });

  const { validatePackagedPetAssets } = await loadDesktopPetAssetValidator(ROOT);
  const petAssets = validatePackagedPetAssets(
    path.join(ROOT, "desktop", "assets", "pets"),
    {
      readFile: (filePath) => readFileSync(filePath, "utf8"),
      exists: existsSync,
      size: (filePath) => statSync(filePath).size,
      join: path.join,
    },
  );

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "main", "main.ts")],
    outfile: outMain,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    sourcemap: true,
    // electron is provided by the runtime. Never pull server-only modules if
    // something accidentally imports them — fail the build instead of shipping spi.
    external: [
      "electron",
      // Hard excludes if a bad import sneaks in:
      "@earendil-works/pi-coding-agent",
      "@earendil-works/pi-ai",
      "next",
      "@lydell/node-pty",
      "node-pty",
    ],
    logLevel: "info",
    // Tree-shake aggressively; pet only needs pure observer + desktop modules.
    packages: "bundle",
    // Ensure Electron treats this file as the app entry even when required.
    banner: {
      js: "/* snail-pi-pet main bundle — generated by scripts/build-desktop-pet.mjs */",
    },
  });

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "preload", "pet-preload.ts")],
    outfile: outPreload,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    sourcemap: true,
    external: ["electron"],
    logLevel: "info",
  });

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "renderer", "pet-app.tsx")],
    outfile: outRenderer,
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "chrome120",
    sourcemap: false,
    // Built-in sprite sheets inline as CSP-friendly data: URLs (img-src data:).
    loader: { ".png": "dataurl", ".webp": "dataurl" },
    logLevel: "info",
  });

  // Small stamp for smoke/debug.
  writeFileSync(
    path.join(ROOT, "desktop", ".build-stamp.json"),
    `${JSON.stringify(
      {
        builtAt: new Date().toISOString(),
        main: "desktop/main/main.js",
        preload: "desktop/preload/pet-preload.js",
        renderer: "desktop/renderer/pet-app.js",
        pets: petAssets,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  console.log("desktop-pet build ok");
  console.log(`  main:     ${path.relative(ROOT, outMain)}`);
  console.log(`  preload:  ${path.relative(ROOT, outPreload)}`);
  console.log(`  renderer: ${path.relative(ROOT, outRenderer)}`);
  console.log(`  pets:     ${petAssets.map((asset) => `${asset.id}:${asset.renderMode}`).join(", ")}`);
}

build().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
