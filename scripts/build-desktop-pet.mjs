/**
 * Bundle desktop pet main, preload, and browser renderer for Electron.
 *
 * Usage: node scripts/build-desktop-pet.mjs
 *        npm run desktop:build
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outMain = path.join(ROOT, "desktop", "main", "main.js");
const outPreload = path.join(ROOT, "desktop", "preload", "pet-preload.js");
const outRenderer = path.join(ROOT, "desktop", "renderer", "pet-app.js");

async function build() {
  mkdirSync(path.dirname(outMain), { recursive: true });
  mkdirSync(path.dirname(outPreload), { recursive: true });

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "main", "main.ts")],
    outfile: outMain,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    sourcemap: true,
    // electron is provided by the runtime. Never pull server-only modules if
    // something accidentally imports them — fail the build instead of shipping spi.
    external: [
      "electron",
      // Hard excludes if a bad import sneaks in:
      "@earendil-works/pi-coding-agent",
      "@earendil-works/pi-ai",
      "next",
      "@lydell/node-pty",
      "node-pty",
    ],
    logLevel: "info",
    // Tree-shake aggressively; pet only needs pure observer + desktop modules.
    packages: "bundle",
    // Ensure Electron treats this file as the app entry even when required.
    banner: {
      js: "/* snail-pi-pet main bundle — generated by scripts/build-desktop-pet.mjs */",
    },
  });

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "preload", "pet-preload.ts")],
    outfile: outPreload,
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    sourcemap: true,
    external: ["electron"],
    logLevel: "info",
  });

  await esbuild.build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, "desktop", "renderer", "pet-app.tsx")],
    outfile: outRenderer,
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "chrome120",
    sourcemap: false,
    logLevel: "info",
  });

  for (const petId of ["snail-default", "snail-classic"]) {
    const manifestPath = path.join(ROOT, "desktop", "assets", "pets", petId, "manifest.json");
    if (!existsSync(manifestPath)) {
      throw new Error(`missing pet manifest: ${petId}`);
    }
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    if (manifest.id !== petId || manifest.version !== 2 || manifest.renderMode !== "css") {
      throw new Error(`invalid pet manifest contract: ${petId}`);
    }
    for (const state of [
      "idle",
      "running",
      "retrying",
      "needs_input",
      "ready",
      "blocked",
      "disconnected",
      "service_not_running",
    ]) {
      if (!manifest.states?.[state]) {
        throw new Error(`pet manifest ${petId} missing state ${state}`);
      }
    }
    if (manifest.sheet || /\.\.\/|file:|https?:/i.test(JSON.stringify(manifest))) {
      throw new Error(`pet manifest ${petId} must stay CSS-only until approved art lands`);
    }
  }

  // Small stamp for smoke/debug.
  writeFileSync(
    path.join(ROOT, "desktop", ".build-stamp.json"),
    `${JSON.stringify(
      {
        builtAt: new Date().toISOString(),
        main: "desktop/main/main.js",
        preload: "desktop/preload/pet-preload.js",
        renderer: "desktop/renderer/pet-app.js",
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  console.log("desktop-pet build ok");
  console.log(`  main:     ${path.relative(ROOT, outMain)}`);
  console.log(`  preload:  ${path.relative(ROOT, outPreload)}`);
  console.log(`  renderer: ${path.relative(ROOT, outRenderer)}`);
}

build().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
